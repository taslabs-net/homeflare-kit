/**
 * `.github/workflows/security.yml`, rendered.
 *
 * ⛔ THIS FILE IS WHY THE RENDERER EXISTS. Measured across 13 repositories on 2026-09-22,
 *   every one of these was a per-repo accident rather than a decision:
 *     · `push: branches: [main]` still present in 5, removed in 8;
 *     · the `concurrency:` block missing entirely in 5 — so a superseded scan ran to
 *       completion holding one of the mini's 3 slots for a result nobody would read;
 *     · `pull-requests: read` missing in 2, which makes every pull-request scan fail 403
 *       before it inspects a single line;
 *     · `gitleaks/gitleaks-action` pinned at `@v2` in 5 and `@v3` in 8, after GitHub
 *       removed the Node 20 runtime v2 needs (2026-09-16);
 *     · the weekly cron at three different minutes.
 *   One renderer makes all thirteen the same file, and the next such fix is one commit.
 */
import type { RepoShape } from './shape.ts';
import { runsOn } from './shape.ts';
import { renderSteps } from './yaml.ts';

/**
 * ⚠️ Off the hour deliberately — `:00` is when every scheduled workflow on GitHub fires
 *   at once, and queue time is the result. One minute for the whole estate: a repository
 *   does NOT get its own, because "which minute is this repo on" is a question with no
 *   useful answer and 13 repos produced 3 different ones by accident.
 */
const CRON = '41 6 * * 1';

const HEADER = `# Secret scanning, on its own schedule and its own check.
#
# 🤖 RENDERED BY @homeflare/config — DO NOT EDIT THIS FILE BY HAND.
#    Its input is this repository's \`repo-shape.ts\`; refresh with \`bun run repo-shape:refresh\`.
#
# ★ SEPARATE FROM ci.yml BY CONCERN. A secret scan answers a different question from "is
#   this code correct", it runs on a schedule as well as on pull requests (a rule added
#   tomorrow can find a secret committed today), and it needs full history, which the CI
#   jobs deliberately do not fetch.
`;

const TRIGGER = `name: security

on:
  # ⛔ NO \`push: branches: [main]\`, for the reason ci.yml gives: main only moves by
  #   squashing a pull request this same workflow already scanned, so the post-merge scan
  #   re-read commits it had just cleared. The weekly cron is what covers "a rule added
  #   tomorrow finds a secret committed today" — and it is the one that fetches full history.
  pull_request:
  schedule:
    - cron: '${CRON}'

permissions:
  contents: read
  # 🔴 gitleaks-action lists pull-request commits through GitHub's API before scanning,
  #   and posts inline annotations. Without this, \`pull_request\` runs fail 403 before
  #   inspecting any code. Two of thirteen repositories were missing it (2026-09-22).
  pull-requests: read

# ⛔ cancel-in-progress IS CONDITIONAL, NOT \`true\`. The scheduled run's ref is
#   refs/heads/main; a plain \`true\` would let anything sharing that group kill the weekly
#   full-history scan. Only pull-request runs are ever cancelled.
concurrency:
  group: security-\${{ github.ref }}
  cancel-in-progress: \${{ github.event_name == 'pull_request' }}
`;

const FETCH_NOTE = `        with:
          # ⛔ FULL HISTORY. A shallow clone scans only the tip, which misses the case that
          #   matters most: a secret added and then removed in a later commit. It is still
          #   in the history, still fetchable, and still compromised.
          fetch-depth: 0`;

const GITLEAKS_NOTE = `      # ⛔ v3, NOT v2. GitHub removed the Node 20 runtime from hosted runners on 2026-09-16
      #   (gitleaks/gitleaks-action's own v3.0.0 migration notes, verified 2026-09-17), so
      #   v2 (\`runs: node20\`) fails outright now, with no opt-out flag. v3 changes only the
      #   runtime to node24 — inputs, outputs and behaviour are unchanged.
      # ★ arm64-SAFE ON THE MINI, verified rather than assumed: v3's src/gitleaks.js builds
      #   its download URL from \`process.arch\`, so the runner asks for
      #   gitleaks_<version>_linux_arm64.tar.gz, an asset its default release publishes
      #   (both read 2026-09-22). Nothing here is hard-coded to x64.
      # ★ No \`GITLEAKS_LICENSE\`: that env var is required only for GitHub Organization
      #   accounts, and \`taslabs-net\` is a personal User account (2026-09-17,
      #   \`gh api users/taslabs-net --jq .type\` -> \`User\`).`;

/** The whole `security.yml` for a shape. */
export function renderSecurity(shape: RepoShape): string {
  const on = runsOn(shape.runner);
  // ⚠️ A GitHub ACTIONS EXPRESSION, NOT A TEMPLATE LITERAL. `${{ … }}` is interpolated by
  //   the Actions runner at job time and must reach the file verbatim, so it is a regular
  //   string on purpose — `no-template-curly-in-string` is warning about exactly the
  //   confusion this comment resolves, and it is right to ask.
  // oxlint-disable-next-line no-template-curly-in-string
  const token = '${{ secrets.GITHUB_TOKEN }}';
  const scheduled =
    shape.runner === 'mini'
      ? `\n    # ⛔ THE SCHEDULED RUN GOES TO THE MINI TOO: if the runner daemon is down this queues\n    #   rather than failing, so a missed weekly scan is silent. homeflare-mini's\n    #   \`ci-runner\` vmalert group is what notices that, not this workflow.`
      : '';

  return `${HEADER}${TRIGGER}
jobs:
  secrets:
    name: secret scan${scheduled}
    runs-on: ${on}
    steps:
${renderSteps([{ uses: 'actions/checkout@v7' }], 3)}
${FETCH_NOTE}

${GITLEAKS_NOTE}
${renderSteps([{ uses: 'gitleaks/gitleaks-action@v3', env: { GITHUB_TOKEN: token } }], 3)}
`;
}
