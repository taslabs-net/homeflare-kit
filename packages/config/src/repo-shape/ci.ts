/**
 * `.github/workflows/ci.yml`, rendered.
 *
 * ★ THE COMMENTS ARE PART OF THE RENDER, NOT DECORATION. Thirteen repositories carried
 *   thirteen hand-edited copies of the same reasoning; measured 2026-09-22, the header
 *   comment alone had four different wordings and the actionlint block had three. Written
 *   here once, every repository gets the same explanation, and correcting it is one edit.
 *
 * ⛔ THE AGGREGATE `ci` JOB IS THE ONLY REQUIRED CHECK. Every other job feeds it through
 *   `needs`, so adding a job never means editing a branch ruleset. `repoShapeChecks()`
 *   returns exactly `['ci', 'secret scan']`, which is what `declareRepoPolicy` requires.
 */
import type { ExtraJob, JobStep, RepoShape } from './shape.ts';
import { nodeMajor, runsOn } from './shape.ts';
import { renderSteps } from './yaml.ts';

/** Bun the whole estate is pinned to. One line, one place. */
export const BUN_VERSION = '1.4.0';
/** actionlint the `workflow lint` job runs, and the mini's job image preloads. */
export const ACTIONLINT_VERSION = '1.7.12';

const CHECKOUT = 'actions/checkout@v7';
const SETUP_BUN = 'oven-sh/setup-bun@v2';
const SETUP_NODE = 'actions/setup-node@v6';

function runnerNote(shape: RepoShape): string {
  if (shape.runner !== 'mini') {
    return "# ⚠️ RUNS ON GitHub-HOSTED `ubuntu-latest`. Only a public repository should: hosted minutes\n#   are refused for this account's private repos (billing lock, 2026-09-22).\n";
  }
  return [
    '# ⚠️ RUNS ON THE MINI (`[self-hosted, homeflare-mini]`): GitHub-hosted runners are refused for',
    '#   this account (billing lock, 2026-09-22), so every job here runs in a one-job Linux arm64',
    "#   container started by homeflare-mini's src/ci-runner (docs/ci-runner.md there). Each action",
    `#   below was checked for linux/arm64. The job image preloads bun ${
      BUN_VERSION
    } where setup-bun`,
    '#   looks, gh, actionlint, gitleaks, typos and shfmt; no node on PATH.',
    '',
  ].join('\n');
}

const HEADER = `# Pull requests: is this code correct?
#
# 🤖 RENDERED BY @homeflare/config — DO NOT EDIT THIS FILE BY HAND.
#    Its input is this repository's \`repo-shape.ts\`. Change that, then:
#        bun run repo-shape:refresh
#    A hand edit is reverted by the next refresh and fails \`bun run check\` before that.
#    A file this repository must own outright is declared as an \`except({...})\` with a
#    reason, which stops the check from comparing it — see @homeflare/config/repo-shape.
#
# ★ SPLIT BY CONCERN, NOT ONE BIG JOB — AND NOT ONE JOB PER COMMAND EITHER: lanes that
#   share a prologue are steps inside \`check\`, so the install is paid once.
# ⛔ EVERY ACTION IS FIRST-PARTY OR THE VENDOR'S OWN, PINNED TO A MAJOR TAG.
`;

const TRIGGER = `name: ci

on:
  # ⛔ NO \`push: branches: [main]\`. Every commit reaches main through a pull request whose
  #   \`ci\` had to be green — the branch ruleset requires it and carries no bypass actors —
  #   so a second run on the squash commit recomputed an answer it already had. Measured
  #   2026-09-15..22 across the estate: 613 of 619 main-push runs had a head_sha identical
  #   to the merge_commit_sha of an already-green PR. That duplication was ~41% of the Mac
  #   mini's entire CI load.
  # ⚠️ WHAT THIS GIVES UP, SAID OUT LOUD: the ~4% of merges whose base DID move between the
  #   PR run and the squash no longer get a post-merge re-test. That run gated nothing — it
  #   reported after main already had the commit — and the next PR, which branches from the
  #   merged main, is what actually catches a semantic conflict.
  pull_request:

permissions:
  contents: read

concurrency:
  group: ci-\${{ github.ref }}
  cancel-in-progress: true
`;

const CHECK_NOTE = `  # ── One job, one install ────────────────────────────────────────────────────
  # ★ WAS 3 SEPARATE JOBS: lint and format, types, tests. They shared an identical
  #   prologue — checkout, setup-bun, \`bun install --frozen-lockfile\` — and the install,
  #   not the check, was the cost: measured on the mini 2026-09-22, install p50 51s /
  #   p90 81s against 1-3s for the command the install existed to enable. 3 jobs meant 3
  #   installs and 3 containers to compute one answer, and on a 3-slot pool that was one
  #   pull request asking for every slot to answer a single question.
  # ⛔ ONE STEP: \`bun run check\`, THE REPOSITORY'S OWN GATE, NOT A COPY OF ITS LANES.
  #   The house rule is that CI runs the same command a person runs, and a workflow that
  #   re-lists \`lint\`, \`types\`, \`test\` is a second copy of that command which can quietly
  #   check LESS than the local gate. Measured 2026-09-22: \`bun run check\` in homeflare-kit
  #   is \`lint && types && build && test\`, and its tests/dist.test.ts SKIPS ITSELF when
  #   dist/ is absent — so a workflow running lint/types/test without the build would drop
  #   that test silently and still report green. homeflare-alerts' check runs
  #   \`check:types\` and \`build:web\`; homeflare-subnet-calc's delegates to \`verify\`. All
  #   fourteen repositories have a \`check\` script and every one is local-only — no network,
  #   no deploy. Checked, not assumed.
  # ★ THE SPLIT OF RESPONSIBILITY: this renderer owns the PLUMBING — triggers, permissions,
  #   concurrency, runner, action versions, the aggregate gate — and the repository owns
  #   WHAT ITS GATE RUNS, in package.json, where a change to it shows up in that
  #   repository's own diff rather than in a workflow nobody reads.
  # ⚠️ THE TRADE, STATED: a red X says \`check\` rather than naming the lane. \`bun run check\`
  #   short-circuits on the first failure and its output names the lane, which is the same
  #   signal a person gets locally.`;

const WORKFLOWS_NOTE = `  # ★ \`workflow lint\` STAYS ITS OWN JOB on purpose: it needs no \`bun install\` at all
  #   (actionlint is preloaded on the mini's job image — measured 5s end to end), so
  #   folding it into \`check\` would make a YAML-only change pay the install for nothing.`;

const ACTIONLINT_NOTE = `      # ⛔ THERE IS NO FIRST-PARTY actionlint ACTION, and the npm package by that name is
      #   an unrelated wasm port with no \`bin\`. The vendor's own documented CI path is
      #   \`download-actionlint.bash\` — but that script does NOT verify a checksum (read at
      #   the v${ACTIONLINT_VERSION} tag, 2026-09-16: \`curl -L "$url" | tar xvz\`, no sha256sum anywhere).
      #   rhysd's releases DO publish a \`_checksums.txt\` per version; this verifies against
      #   that instead of trusting the tarball on receipt.
      # ⚠️ ARCH FROM THE RUNNER, NOT HARD-CODED: the mini's runners are arm64, and an amd64
      #   binary fails with "exec format error" (the checksum file lists both).`;

const INSTALL_ACTIONLINT = `set -euo pipefail
version=${ACTIONLINT_VERSION}
if command -v actionlint >/dev/null 2>&1 &&
  [ "$(actionlint -version 2>/dev/null | sed -n 1p)" = "\${version}" ]; then
  cp "$(command -v actionlint)" ./actionlint
  exit 0
fi
case "$(uname -m)" in
  x86_64) arch=amd64 ;;
  aarch64 | arm64) arch=arm64 ;;
  *) echo "unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac
file="actionlint_\${version}_linux_\${arch}.tar.gz"
base="https://github.com/rhysd/actionlint/releases/download/v\${version}"
curl -sSfLO "\${base}/\${file}"
curl -sSfLO "\${base}/actionlint_\${version}_checksums.txt"
grep " \${file}\\$" "actionlint_\${version}_checksums.txt" | sha256sum -c -
tar xzf "\${file}" actionlint`;

const AGGREGATE_NOTE = `  # ── The one check a branch rule can require ─────────────────────────────────
  # ★ A single required check that depends on all of them. Without this, adding a job
  #   means editing the branch ruleset too, and forgetting to means the new job is
  #   advisory without anyone noticing.
  # ⛔ FAILS ON ANYTHING OTHER THAN success, INCLUDING skipped. A job result has exactly
  #   four values: success, failure, cancelled, skipped. Checking only the first two lets
  #   a skipped job — a bad \`if:\` condition, a misconfigured dependency, a runner picking
  #   up nothing — report this aggregate green with a required job never having run.`;

const VERIFY = `if [ "\${{ contains(needs.*.result, 'failure') }}" = "true" ] || \\
   [ "\${{ contains(needs.*.result, 'cancelled') }}" = "true" ] || \\
   [ "\${{ contains(needs.*.result, 'skipped') }}" = "true" ]; then
  echo "one or more required jobs did not succeed: \${{ toJSON(needs.*.result) }}" >&2
  exit 1
fi`;

const NODE_NOTE = `      # ⛔ REAL NODE, NOT BUN'S SHIM, AND ONLY WHERE THE GATE NEEDS IT. The mini's job
      #   image has no node on PATH (ubuntu-latest always did), so a repository whose own
      #   \`check\` spawns \`node\` — or whose framework demands a Node runtime — fails with
      #   \`Executable not found in $PATH: "node"\` without this. Declared as \`node:\` in
      #   repo-shape.ts, so it is one input rather than a hand-edited block per repository.
      # ⚠️ NO PACKAGE-MANAGER CACHE: bun does the installing, so priming npm's cache costs
      #   time and caches nothing anything here reads.`;

function prologue(shape: RepoShape): string {
  const node = nodeMajor(shape);
  const bun: JobStep[] = [
    { uses: SETUP_BUN, with: { 'bun-version': BUN_VERSION } },
    { run: 'bun install --frozen-lockfile' },
  ];
  if (node === undefined) return renderSteps([{ uses: CHECKOUT }, ...bun], 3);
  return [
    renderSteps([{ uses: CHECKOUT }], 3),
    NODE_NOTE,
    renderSteps(
      [{ uses: SETUP_NODE, with: { 'node-version': node, 'package-manager-cache': 'false' } }],
      3,
    ),
    renderSteps(bun, 3),
  ].join('\n');
}

function renderExtraJob(job: ExtraJob, shape: RepoShape, on: string): string {
  const needs =
    (job.needs ?? []).length === 0 ? '' : `    needs: [${(job.needs ?? []).join(', ')}]\n`;
  // ★ A TIMEOUT IS THE JOB'S, NOT THE SHAPE'S. Only a job that starts something with its
  //   own wait needs one, and it is rendered where a reader looks for it.
  const timeout = job.timeout === undefined ? '' : `    timeout-minutes: ${job.timeout}\n`;
  const steps =
    job.bun === false
      ? renderSteps([{ uses: CHECKOUT }, ...job.steps], 3)
      : [prologue(shape), renderSteps(job.steps, 3)].join('\n');
  // ★ The stated reason is rendered into the file. A job nobody can explain is a job
  //   nobody dares delete, so the explanation travels with it.
  return `  # ★ NOT PART OF THE STANDARD SHAPE — ${job.reason}
  ${job.id}:
    name: ${job.name}
${needs}    runs-on: ${on}
${timeout}    steps:
${steps}
`;
}

/** The whole `ci.yml` for a shape. */
export function renderCi(shape: RepoShape): string {
  const on = runsOn(shape.runner);
  const extras = shape.extraJobs ?? [];
  const needs = ['check', 'workflows', ...extras.map((job) => job.id)];

  return `${HEADER}${runnerNote(shape)}${TRIGGER}
jobs:
${CHECK_NOTE}
  check:
    name: check
    runs-on: ${on}
    steps:
${prologue(shape)}
${renderSteps([{ run: 'bun run check' }], 3)}

${WORKFLOWS_NOTE}
  workflows:
    name: workflow lint
    runs-on: ${on}
    steps:
${renderSteps([{ uses: CHECKOUT }], 3)}
${ACTIONLINT_NOTE}
${renderSteps([{ name: 'Install actionlint (checksum-verified)', run: INSTALL_ACTIONLINT }], 3)}
${renderSteps([{ name: 'Lint workflows', run: './actionlint -color' }], 3)}

${extras.map((job) => `${renderExtraJob(job, shape, on)}\n`).join('')}${AGGREGATE_NOTE}
  ci:
    name: ci
    if: always()
    needs: [${needs.join(', ')}]
    runs-on: ${on}
    steps:
${renderSteps([{ name: 'Verify every job succeeded', run: VERIFY }], 3)}
`;
}
