/**
 * A retired rendered path — one `render.ts` stopped emitting — is a fossil until
 * `refreshRepoShape` deletes it, and it can only delete what it can prove it once wrote.
 *
 * ★ EVERY TEST HERE WRITES A REAL DIRECTORY AND READS IT BACK, same reasoning as
 *   `repo-shape-drift.test.ts`: "a committed file was deleted" is exactly the kind of claim
 *   a mocked filesystem cannot be wrong about in the way a real one can.
 */
import { afterEach, describe, expect, test } from 'bun:test';
import { rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import {
  GENERATED_FILE_MARKER,
  RENDERED_PATHS,
  RETIRED_FILES,
  type RepoShape,
  driftInRepoShape,
  refreshRepoShape,
  repoShapeCli,
  wasRenderedByUs,
} from '../src/repo-shape.ts';

const SHAPE: RepoShape = {
  owner: 'taslabs-net',
  publishes: false,
  repository: 'homeflare-proxmox',
  runner: 'mini',
};

// ⛔ THE FIX TARGETS THIS ONE. If a second retirement is ever added, this file's tests
//   should still pass unchanged — they read `RETIRED_FILES[0]`, not the literal path.
const RETIRED = RETIRED_FILES[0];
if (RETIRED === undefined) throw new Error('repo-shape: expected at least one retired file');

const made: string[] = [];

async function scratch(): Promise<string> {
  const dir = `${tmpdir()}/repo-shape-retired-${crypto.randomUUID()}`;
  made.push(dir);
  return dir;
}

afterEach(async () => {
  await Promise.all(made.splice(0).map((dir) => rm(dir, { force: true, recursive: true })));
});

describe('the one-way door', () => {
  test('no path is both rendered today and retired — that would fight itself on refresh', () => {
    const retiredPaths = RETIRED_FILES.map((file) => file.path);
    for (const path of retiredPaths) expect(RENDERED_PATHS).not.toContain(path);
  });
});

describe('wasRenderedByUs', () => {
  test('true for text carrying the generated-file header', () => {
    expect(wasRenderedByUs(`# ${GENERATED_FILE_MARKER} — DO NOT EDIT THIS FILE BY HAND.\n`)).toBe(
      true,
    );
  });

  test('true when the header is not the first line, same as every real renderer', () => {
    // ★ Every renderer in this directory puts the marker on the THIRD line (a title line,
    //   a bare `#`, then the marker) — never the first. A first-line-only check would fail
    //   every real rendered file; this asserts the guard does not make that mistake.
    expect(
      wasRenderedByUs(`# Some title\n#\n# ${GENERATED_FILE_MARKER} — DO NOT EDIT.\n#    more\n`),
    ).toBe(true);
  });

  test('false for ordinary hand-written text, header text included as a red herring', () => {
    expect(wasRenderedByUs('# a workflow someone wrote by hand\n')).toBe(false);
    expect(wasRenderedByUs('# this repo was rendered once, ages ago\n')).toBe(false);
  });

  test('false when the marker is only mentioned mid-sentence, not its own header line', () => {
    // ⛔ ADVERSARIAL CASE, caught in review before this shipped: a hand-written comment
    //   that merely TALKS ABOUT the marker must not read as "carries the header" — only a
    //   line that STARTS with it does. Otherwise explaining, in prose, why a file is kept
    //   by hand is exactly what gets it deleted.
    expect(
      wasRenderedByUs(
        `# this file used to be ${GENERATED_FILE_MARKER} before it was retired; kept by hand now\n`,
      ),
    ).toBe(false);
  });
});

describe('refreshRepoShape deletes a retired path only when it can prove it rendered it', () => {
  test('a file carrying the header is removed', async () => {
    const dir = await scratch();
    const target = `${dir}/${RETIRED.path}`;
    await Bun.write(target, `# ${GENERATED_FILE_MARKER} — DO NOT EDIT THIS FILE BY HAND.\n`);

    const result = await refreshRepoShape(dir, SHAPE);

    expect(result.removed).toEqual([RETIRED.path]);
    expect(result.refused).toEqual([]);
    expect(await Bun.file(target).exists()).toBe(false);
  });

  test('a hand-written file at the same path is refused, never deleted', async () => {
    const dir = await scratch();
    const target = `${dir}/${RETIRED.path}`;
    const handWritten = '# this repository still wants auto-merge here, kept on purpose\n';
    await Bun.write(target, handWritten);

    const result = await refreshRepoShape(dir, SHAPE);

    expect(result.refused).toEqual([RETIRED.path]);
    expect(result.removed).toEqual([]);
    expect(await Bun.file(target).text()).toBe(handWritten);
  });

  test('a repository that never had the retired file is unaffected', async () => {
    const dir = await scratch();
    const result = await refreshRepoShape(dir, SHAPE);

    expect(result.removed).toEqual([]);
    expect(result.refused).toEqual([]);
    expect(await Bun.file(`${dir}/${RETIRED.path}`).exists()).toBe(false);
  });
});

describe('driftInRepoShape flags a retired path that is still present', () => {
  test('carrying the header — present is present, proof is refresh’s job, not the check’s', async () => {
    const dir = await scratch();
    // ⚠️ REFRESH FIRST, WRITE THE FOSSIL AFTER: refreshing again would delete a file that
    //   carries the header (that is the whole point of the other describe block above), so
    //   the fossil has to land after the only refresh call this test makes.
    await refreshRepoShape(dir, SHAPE);
    await Bun.write(
      `${dir}/${RETIRED.path}`,
      `# ${GENERATED_FILE_MARKER} — DO NOT EDIT THIS FILE BY HAND.\n`,
    );

    const report = await driftInRepoShape(dir, SHAPE);

    const problem = report.problems.find((p) => p.startsWith(RETIRED.path));
    expect(problem).toBeDefined();
    expect(problem).toContain(`@homeflare/config@${RETIRED.retiredIn}`);
    expect(problem).toContain('bun run repo-shape:refresh');
  });

  test('hand-written — still flagged, so a fossil is visible even where refresh cannot fix it', async () => {
    const dir = await scratch();
    await Bun.write(`${dir}/${RETIRED.path}`, '# kept on purpose\n');
    await refreshRepoShape(dir, SHAPE);

    const report = await driftInRepoShape(dir, SHAPE);
    expect(report.problems.some((p) => p.startsWith(RETIRED.path))).toBe(true);
  });

  test('a repository without the retired path reports nothing about it', async () => {
    const dir = await scratch();
    await refreshRepoShape(dir, SHAPE);

    const report = await driftInRepoShape(dir, SHAPE);
    expect(report.problems.some((p) => p.startsWith(RETIRED.path))).toBe(false);
  });
});

describe('the CLI, end to end', () => {
  test('--check fails on the fossil, and passes once a refresh removes it', async () => {
    const dir = await scratch();
    await Bun.write(
      `${dir}/${RETIRED.path}`,
      `# ${GENERATED_FILE_MARKER} — DO NOT EDIT THIS FILE BY HAND.\n`,
    );

    expect(await repoShapeCli(dir, SHAPE, ['--check'])).toBe(1);
    expect(await repoShapeCli(dir, SHAPE, [])).toBe(0); // the refresh that removes it
    expect(await repoShapeCli(dir, SHAPE, ['--check'])).toBe(0);
    expect(await Bun.file(`${dir}/${RETIRED.path}`).exists()).toBe(false);
  });
});
