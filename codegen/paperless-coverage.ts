/**
 * `docs/paperless-coverage.md` — what this package can write in Paperless, and what it cannot.
 * Owner column derived the same way `netbox-coverage.ts` derives it: the file that NAMES the
 * endpoint key, found by the same scan the generator uses.
 */
import type { CoverageInput, CoverageRow } from './paperless-render.ts';

const pct = (part: number, whole: number): string =>
  whole === 0 ? '0%' : `${((part / whole) * 100).toFixed(1)}%`;

const rowLine = (row: CoverageRow): string =>
  `| \`${row.key}\` | ${row.params} | ${row.enforced} | ${row.recordedOnly} | \`${row.source}\` |`;

const areaLine = (a: { readonly area: string; readonly endpoints: number }): string =>
  `| \`${a.area}\` | ${a.endpoints} |`;

export const renderCoverage = (input: CoverageInput): string => {
  const { entry, rows, writeEndpoints, writePaths, areas } = input;
  const tabled = rows.length;
  const params = rows.reduce((n, r) => n + r.params, 0);
  const enforced = rows.reduce((n, r) => n + r.enforced, 0);
  const recorded = rows.reduce((n, r) => n + r.recordedOnly, 0);
  return `# Paperless API coverage

<!-- GENERATED by codegen/paperless.ts — DO NOT EDIT BY HAND.
     Regenerate: bun codegen/paperless.ts   ·   Verify: bun codegen/paperless.ts --check -->

Generated from the vendor document recorded in
[\`codegen/manifest.json\`](../codegen/manifest.json):

- **${entry.product}** \`${entry.version}\` — sha256 \`${entry.sha256.slice(0, 16)}…\`
- ${entry.sourceRole}
- \`${entry.sourcePath}\`

## The headline

| | count |
| --- | ---: |
| write endpoints Paperless publishes (POST/PUT/PATCH/DELETE) | ${writeEndpoints} |
| distinct write paths | ${writePaths} |
| endpoints tabled here | ${tabled} (${pct(tabled, writeEndpoints)}) |
| body parameters in those tables | ${params} |
| …enforced at plan time | ${enforced} |
| …recorded but NOT enforced | ${recorded} |

⛔ **${writeEndpoints - tabled} write endpoints are untabled and therefore unchecked at plan
time.** This slice covers the taxonomy family only (Tag, DocumentType, StoragePath,
CustomField) — Documents, Workflows and mail accounts are deferred.

## Tabled endpoints

| endpoint | body params | enforced | recorded only | declared in |
| --- | ---: | ---: | ---: | --- |
${rows.map(rowLine).join('\n')}

## The write surface, by Paperless area

| area | write endpoints |
| --- | ---: |
${areas.map(areaLine).join('\n')}

## What this report does NOT tell you

- **Whether Paperless is reachable right now.** The document is a schema read at a point in
  time, not a live probe on every regeneration.
- **Whether a tabled rule is sufficient.** Paperless also enforces uniqueness on
  \`(name, owner)\`, a custom field's \`select_options\` shape, and other rules no schema states —
  those still arrive as a server-side 400.

Merged table digest: \`${input.digest}\`.
`;
};
